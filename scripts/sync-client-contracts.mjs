// Run from any directory with node scripts/sync-client-contracts.mjs [--check].
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
const banner = '// Generated by scripts/sync-client-contracts.mjs from the .NET contracts.';
function emit(file, lines) {
    const path = resolve(root, file);
    const content = [banner, ...lines, ''].join('\n');
    if (process.argv.includes('--check')) {
        if (readFileSync(path, 'utf8').replaceAll('\r\n', '\n') !== content)
            throw new Error('Run node scripts/sync-client-contracts.mjs to update ' + file);
    } else {
        writeFileSync(path, content);
    }
}
function literals(file) {
    const source = readFileSync(resolve(root, file), 'utf8');
    return Object.fromEntries([...source.matchAll(/public const string (\w+) = "([^"]+)";/g)].map(([, name, value]) => [name, value]));
}
function required(values, key) {
    if (!Object.hasOwn(values, key)) throw new Error('Missing contract member ' + key);
    return values[key];
}
function tsObject(name, values) {
    return ['export const ' + name + ' = {', ...Object.entries(values).map(([key, value]) => '    ' + key + ': ' + JSON.stringify(value) + ','), '} as const;'];
}

const plugins = 'src/Plugins';
const ids = {};
const names = {};
for (const entry of readdirSync(resolve(root, plugins), { withFileTypes: true }).filter(entry => entry.isDirectory()).sort((a, b) => a.name.localeCompare(b.name, 'en'))) {
    const dir = plugins + '/' + entry.name + '/Contracts';
    const identity = readdirSync(resolve(root, dir)).find(name => name.endsWith('Identity.cs'));
    if (identity) {
        const members = literals(dir + '/' + identity);
        const id = required(members, 'Id');
        ids[entry.name + 'Id'] = id;
        names[id] = members.ShortName ?? required(members, 'DisplayName');
    }
}
for (const client of ['Mobile', 'Widget']) {
    emit('src/' + client + '/src/pluginIds.ts', Object.entries(ids).map(([key, value]) => 'export const ' + key + ' = ' + JSON.stringify(value) + ';'));
}

emit('src/Mobile/src/pluginNames.ts', ['export const pluginNames: Readonly<Record<string, string>> = ' + JSON.stringify(names, null, 4) + ';']);

const modelFile = plugins + '/Msi/Plugin/Device/MsiPsuModels.cs';
const modelSource = readFileSync(resolve(root, modelFile), 'utf8');
const modelNames = literals(modelFile);
const models = [...modelSource.matchAll(/public const int (\w+)ProductId = 0x([0-9a-fA-F]+);/g)]
    .map(([, model, productId]) => ['pid_' + productId.toLowerCase(), 'MSI ' + required(modelNames, model + 'Name')]);
if (!models.length) throw new Error('No MSI PSU models found in ' + modelFile);
const msi = literals(plugins + '/Msi/Contracts/MsiIdentity.cs');
const asusAlerts = literals(plugins + '/Asus/Contracts/Warnings/AsusAlertKinds.cs');
const wireAlerts = readFileSync(resolve(root, plugins + '/WireView/Contracts/Warnings/WireViewWarningIds.cs'), 'utf8');
const profileSuffix = /ProfilePinOvercurrent = WireViewIdentity.Id \+ "([^"]+)"/.exec(wireAlerts)?.[1];
if (!profileSuffix) throw new Error('Missing WireView profile warning ID');
emit('src/Widget/src/panels/hardwareLabels.ts', [
    ...tsObject('hardwareLabels', {
        MsiFamily: required(msi, 'PluginName'), Astral: names[ids.AsusId], WireView: names[ids.WireViewId],
        ImbalanceAlert: required(asusAlerts, 'CurrentImbalance'), ProfileOvercurrentAlert: ids.WireViewId + profileSuffix,
    }),
    'export const msiModels = ' + JSON.stringify(Object.fromEntries(models), null, 4) + ' as const;',
]);

const monitoring = 'src/Common/Contracts/Monitoring/';
const routes = literals(monitoring + 'ServiceRoutes.cs');
const wireView = literals(plugins + '/WireView/Contracts/WireViewIdentity.cs');
const widgetRoutes = Object.fromEntries(['Health', 'Plugins', 'Configuration', 'Sensors'].map(key => [key, '/' + required(routes, key)]));
widgetRoutes.WireViewConfiguration = widgetRoutes.Plugins + '/' + ids.WireViewId + required(wireView, 'DeviceConfigPath');
emit('src/Widget/src/transport/serviceRoutes.ts', tsObject('serviceRoutes', widgetRoutes));

const release = literals('src/Common/Contracts/Updates/ReleaseManifest.cs');
const releaseFields = Object.fromEntries(['RepositoryUrl', 'ManifestUrl', 'TagPath'].map(key => [key, required(release, key)]));
releaseFields.LegacyRepositoryUrl = required(release, 'LegacyRepositoryUrl');
emit('src/Widget/src/updates/releaseLinks.ts', tsObject('releaseLinks', releaseFields));

const mobile = literals(monitoring + 'MobileProtocol.cs');
emit('src/Mobile/src/mobileProtocol.ts', tsObject('mobileProtocol', mobile));
const native = ['Session', 'Incidents', 'RegistrationV2', 'Pairing', 'CompletePairing', 'WarningActions', 'RunWarningAction'].map(key => [key[0].toLowerCase() + key.slice(1), required(mobile, key)]);
const transport = 'src/Mobile/modules/rtxlens-transport/';
emit(transport + 'ios/MobileRoutes.swift', ['enum MobileRoutes {', ...native.map(([key, value]) => '    static let ' + key + ' = ' + JSON.stringify(value)), '}']);
emit(transport + 'android/src/main/java/com/rtxlens/transport/MobileRoutes.kt', ['package com.rtxlens.transport', '', 'internal object MobileRoutes {', ...native.map(([key, value]) => '    const val ' + key + ' = ' + JSON.stringify(value)), '}']);
